std::string GetEnvA(const char* name) {
    char buffer[1024] = {};
    DWORD size = GetEnvironmentVariableA(name, buffer, static_cast<DWORD>(sizeof(buffer)));
    if (size == 0 || size >= sizeof(buffer)) return std::string();
    return std::string(buffer, size);
}

std::wstring GetEnvW(const wchar_t* name) {
    wchar_t buffer[32768] = {};
    DWORD size = GetEnvironmentVariableW(name, buffer, static_cast<DWORD>(_countof(buffer)));
    if (size == 0 || size >= _countof(buffer)) return std::wstring();
    return std::wstring(buffer, size);
}

bool ReadFileBytes(const std::wstring& path, std::vector<BYTE>& out) {
    HANDLE file = CreateFileW(path.c_str(), GENERIC_READ, FILE_SHARE_READ | FILE_SHARE_WRITE | FILE_SHARE_DELETE,
                              nullptr, OPEN_EXISTING, FILE_ATTRIBUTE_NORMAL, nullptr);
    if (file == INVALID_HANDLE_VALUE) return false;
    LARGE_INTEGER size = {};
    if (!GetFileSizeEx(file, &size) || size.QuadPart <= 0 || size.QuadPart > 4 * 1024 * 1024) {
        CloseHandle(file);
        return false;
    }
    out.resize(static_cast<size_t>(size.QuadPart));
    DWORD read = 0;
    bool ok = ReadFile(file, out.data(), static_cast<DWORD>(out.size()), &read, nullptr) != FALSE && read == out.size();
    CloseHandle(file);
    return ok;
}

// Minimal string-value extractor for identity.json. The file is generated by
// the wrapper, so only flat top-level string members are needed.
bool JsonString(const std::string& text, const char* key, std::string& value) {
    std::string needle = "\"";
    needle += key;
    needle += "\"";
    size_t pos = text.find(needle);
    if (pos == std::string::npos) return false;
    pos = text.find(':', pos + needle.size());
    if (pos == std::string::npos) return false;
    ++pos;
    while (pos < text.size() && (text[pos] == ' ' || text[pos] == '\t' || text[pos] == '\r' || text[pos] == '\n')) ++pos;
    if (pos >= text.size()) return false;
    if (text[pos] == '"') {
        ++pos;
        std::string result;
        while (pos < text.size() && text[pos] != '"') {
            if (text[pos] == '\\' && pos + 1 < text.size()) ++pos;
            result.push_back(text[pos++]);
        }
        value = result;
        return true;
    }
    size_t end = text.find_first_of(",}\r\n", pos);
    if (end == std::string::npos) end = text.size();
    value = text.substr(pos, end - pos);
    while (!value.empty() && (value.back() == ' ' || value.back() == '\t')) value.pop_back();
    return !value.empty();
}

uint64_t Fnv1a(const std::string& value) {
    uint64_t hash = 1469598103934665603ULL;
    for (unsigned char c : value) {
        hash ^= c;
        hash *= 1099511628211ULL;
    }
    return hash;
}

std::string HexFromHash(const std::string& seed, size_t chars) {
    uint64_t h1 = Fnv1a(seed);
    uint64_t h2 = Fnv1a(seed + "|2");
    char buffer[33] = {};
    std::snprintf(buffer, sizeof(buffer), "%016llx%016llx",
                  static_cast<unsigned long long>(h1), static_cast<unsigned long long>(h2));
    std::string result(buffer);
    if (result.size() < chars) return result;
    return result.substr(0, chars);
}

std::string ToUpperHex(std::string value) {
    for (char& c : value) {
        if (c >= 'a' && c <= 'f') c = static_cast<char>(c - 'a' + 'A');
    }
    return value;
}

