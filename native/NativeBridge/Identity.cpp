bool ProfileIdentity::Load() {
    profileDir = GetEnvW(L"CAC_PROFILE_DIR");
    const std::wstring identityPath = GetEnvW(L"CAC_PROFILE_IDENTITY");

    std::string document;
    if (!identityPath.empty()) {
        std::vector<BYTE> bytes;
        if (ReadFileBytes(identityPath, bytes)) {
            size_t offset = 0;
            if (bytes.size() >= 3 && bytes[0] == 0xEF && bytes[1] == 0xBB && bytes[2] == 0xBF) offset = 3;
            document.assign(reinterpret_cast<const char*>(bytes.data() + offset), bytes.size() - offset);
        }
    }

    JsonString(document, "hostname", hostname);
    JsonString(document, "machine_id", machineId);
    JsonString(document, "stable_id", stableId);
    JsonString(document, "mac_address", mac);
    JsonString(document, "disk_serial", diskSerial);
    JsonString(document, "bios_serial", biosSerial);
    JsonString(document, "board_serial", boardSerial);
    JsonString(document, "system_serial", systemSerial);
    JsonString(document, "system_uuid", systemUuid);
    JsonString(document, "processor_id", processorId);
    JsonString(document, "hid_serial", hidSerial);
    JsonString(document, "volume_serial", volumeSerialHex_);

    const std::string envHost = GetEnvA("CAC_HOSTNAME");
    const std::string envMachine = GetEnvA("CAC_MACHINE_ID");
    const std::string envMac = GetEnvA("CAC_MAC");
    if (!envHost.empty()) hostname = envHost;
    if (!envMachine.empty()) machineId = envMachine;
    if (!envMac.empty()) mac = envMac;
    username = GetEnvA("CAC_USERNAME");

    if (machineId.empty()) machineId = HexFromHash("cac-fallback", 32);
    if (stableId.empty()) stableId = HexFromHash(machineId + "|stable", 32);

    if (hostname.empty()) hostname = "host-" + HexFromHash(machineId + "|host", 8);
    if (username.empty()) username = "user-" + HexFromHash(machineId + "|user", 8);
    if (mac.empty()) {
        const std::string hex = HexFromHash(machineId + "|mac", 10);
        mac = "02:";
        for (size_t i = 0; i + 1 < hex.size(); i += 2) {
            if (i) mac += ':';
            mac += hex.substr(i, 2);
        }
    }
    if (diskSerial.empty()) diskSerial = "WD-" + HexFromHash(machineId + "|disk", 12);
    if (biosSerial.empty()) biosSerial = "PF" + HexFromHash(machineId + "|bios", 10);
    if (boardSerial.empty()) boardSerial = "MB" + HexFromHash(machineId + "|board", 10);
    if (systemSerial.empty()) systemSerial = "SYS" + HexFromHash(machineId + "|system", 10);
    if (systemUuid.empty()) systemUuid = ToUpperHex(HexFromHash(machineId + "|uuid", 32));
    if (processorId.empty()) processorId = ToUpperHex(HexFromHash(machineId + "|cpu", 16));
    if (hidSerial.empty()) hidSerial = "HID" + ToUpperHex(HexFromHash(machineId + "|hid", 10));
    if (volumeSerialHex_.empty()) volumeSerialHex_ = ToUpperHex(HexFromHash(machineId + "|volume", 8));

    // MAC: only a syntactically valid unicast address is applied.
    unsigned int b[6] = {};
    if (std::sscanf(mac.c_str(), "%2x:%2x:%2x:%2x:%2x:%2x", &b[0], &b[1], &b[2], &b[3], &b[4], &b[5]) == 6) {
        for (int i = 0; i < 6; ++i) macBytes[i] = static_cast<BYTE>(b[i]);
        hasMac = true;
    }

    volumeSerial = static_cast<DWORD>(std::strtoul(volumeSerialHex_.c_str(), nullptr, 16));
    if (volumeSerial == 0) volumeSerial = static_cast<DWORD>(Fnv1a(machineId) & 0xFFFFFFFFu);
    return true;
}

ProfileIdentity& ProfileIdentity::Get() {
    static ProfileIdentity instance;
    static bool loaded = false;
    if (!loaded) {
        instance.Load();
        loaded = true;
    }
    return instance;
}
